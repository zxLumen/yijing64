/** 与占卜强无关的客观事实 / 实时信息信号词（命中即判无关）。 */
const UNRELATED = ['天气', '气温', '今天几号', '今天日期', '今天是几号', '今天星期几', '星期几', '现在几点', '现在几点了', '几点钟', '新闻', '政治']

/** 占卜相关信号词。 */
const RELATED = [
  '卦', '爻', '占卜', '起卦', '解卦', '预测', '运势', '事业', '财运', '工作', '感情', '姻缘', '婚恋', '健康', '学业', '考运', '考试', '吉凶', '祸福', '方位', '择日',
  '正缘', '贵人', '小人', '流年', '太岁', '风水', '八字', '命理', '犯太岁', '搬家', '出行', '出门', '远行', '出差', '旅行', '面试', '跳槽', '求职', '找工作', '升职',
  '合作', '买房', '装修', '相亲', '手术', '治病', '康复', '官司', '测', '算一卦', '摇卦', '铜钱',
]

export const REFUSAL = '这似乎与占卜无关。我是《周易》起卦解卦助手，只回答卦象、运势与所问之事相关的问题，请换个问题试试。'

/** @param {string} question @returns {boolean} 是否放行给模型 */
export const isRelevant = (question) => {
  const text = question.trim()
  if (!text) return true
  if (UNRELATED.some((k) => text.includes(k)) && !RELATED.some((k) => text.includes(k))) return false
  return true
}
